param([switch]$Offline, [switch]$DebugNative)
$ErrorActionPreference = 'Stop'
$projectRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
Push-Location -LiteralPath $projectRoot
try {
    if (-not $env:ANDROID_HOME) { $env:ANDROID_HOME = Join-Path $env:LOCALAPPDATA 'Android/Sdk' }
    if (-not $env:NDK_HOME) {
        $ndk = Get-ChildItem -LiteralPath (Join-Path $env:ANDROID_HOME 'ndk') -Directory | Sort-Object Name -Descending | Select-Object -First 1
        if (-not $ndk) { throw 'Install Android NDK 28 or later.' }
        $env:NDK_HOME = $ndk.FullName
    }
    if (-not $env:JAVA_HOME) {
        $knownJdk = Join-Path $env:USERPROFILE '.jdks/corretto-23.0.2'
        if (Test-Path -LiteralPath $knownJdk) { $env:JAVA_HOME = $knownJdk } else { throw 'Set JAVA_HOME to a JDK compatible with Gradle 8.14.3 (17–23).' }
    }
    $tempDir = Join-Path $projectRoot 'build-temp'
    New-Item -ItemType Directory -Force -Path $tempDir | Out-Null
    $env:TEMP = $tempDir
    $env:TMP = $tempDir
    $env:CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER = Join-Path $env:NDK_HOME 'toolchains/llvm/prebuilt/windows-x86_64/bin/aarch64-linux-android26-clang.cmd'
    $env:CC_aarch64_linux_android = $env:CARGO_TARGET_AARCH64_LINUX_ANDROID_LINKER
    $env:AR_aarch64_linux_android = Join-Path $env:NDK_HOME 'toolchains/llvm/prebuilt/windows-x86_64/bin/llvm-ar.exe'
    $cargoArgs = @('build','-p','elsewhere','--target','aarch64-linux-android','--lib','--features','tauri/custom-protocol','--locked')
    if (-not $DebugNative) { $cargoArgs += '--release' }
    if ($Offline) { $cargoArgs += '--offline' }
    & cargo @cargoArgs
    if ($LASTEXITCODE -ne 0) { throw 'Android Rust build failed.' }
    # Generate native plugin project references from the actual Cargo resolution.
    # This also makes the checkout portable across registry locations.
    $metadataArgs = @('metadata','--format-version','1','--locked')
    if ($Offline) { $metadataArgs += '--offline' }
    $metadata = (& cargo @metadataArgs) | ConvertFrom-Json
    if ($LASTEXITCODE -ne 0) { throw 'Could not resolve Android native dependencies.' }
    $settingsLines = @('// Generated by scripts/build-android.ps1 from Cargo metadata.')
    $dependencyLines = @('// Generated by scripts/build-android.ps1.', 'val implementation = configurations.getByName("implementation")', 'dependencies {', '  implementation("androidx.lifecycle:lifecycle-process:2.10.0")')
    foreach ($packageName in @('tauri','tauri-plugin-dialog','tauri-plugin-fs')) {
        $package = $metadata.packages | Where-Object name -eq $packageName | Select-Object -First 1
        if (-not $package) { throw "Missing package $packageName" }
        $nativePath = Join-Path (Split-Path $package.manifest_path) $(if ($packageName -eq 'tauri') { 'mobile/android' } else { 'android' })
        if (-not (Test-Path -LiteralPath $nativePath)) { throw "Missing Android project $nativePath" }
        $nativePath = $nativePath.Replace('\','/')
        $gradleName = if ($packageName -eq 'tauri') { 'tauri-android' } else { $packageName }
        $settingsLines += "include ':$gradleName'"
        $settingsLines += "project(':$gradleName').projectDir = new File('$nativePath')"
        $dependencyLines += '  implementation(project(":' + $gradleName + '"))'
    }
    $dependencyLines += '}'
    Set-Content -LiteralPath (Join-Path $projectRoot 'src-tauri/gen/android/tauri.settings.gradle') -Value ($settingsLines -join "`n") -Encoding utf8
    Set-Content -LiteralPath (Join-Path $projectRoot 'src-tauri/gen/android/app/tauri.build.gradle.kts') -Value ($dependencyLines -join "`n") -Encoding utf8
    $jniDir = Join-Path $projectRoot 'src-tauri/gen/android/app/src/main/jniLibs/arm64-v8a'
    New-Item -ItemType Directory -Force -Path $jniDir | Out-Null
    $nativeProfile = if ($DebugNative) { 'debug' } else { 'release' }
    Copy-Item -LiteralPath (Join-Path $projectRoot "target/aarch64-linux-android/$nativeProfile/libelsewhere_app.so") -Destination (Join-Path $jniDir 'libelsewhere_app.so')
    & (Join-Path $env:NDK_HOME 'toolchains/llvm/prebuilt/windows-x86_64/bin/llvm-strip.exe') --strip-debug (Join-Path $jniDir 'libelsewhere_app.so')
    if ($LASTEXITCODE -ne 0) { throw 'Could not strip native debug symbols.' }
    Push-Location -LiteralPath (Join-Path $projectRoot 'src-tauri/gen/android')
    try {
        $appConfig=Get-Content -LiteralPath (Join-Path $projectRoot 'src-tauri/tauri.conf.json') -Raw | ConvertFrom-Json
        $appVersion=[Version]$appConfig.version
        $appVersionCode=$appVersion.Major*1000000+$appVersion.Minor*1000+$appVersion.Build
        Set-Content -LiteralPath 'app/tauri.properties' -Value "tauri.android.versionName=$($appConfig.version)`ntauri.android.versionCode=$appVersionCode" -Encoding utf8
        # A clean package prevents stale native-library gaps in incremental APK ZIPs.
        $gradleArgs = @('--no-daemon',':app:clean',':app:assembleArm64Debug','-x','rustBuildArm64Debug')
        if ($Offline) { $gradleArgs += '--offline' }
        & ./gradlew.bat @gradleArgs
        if ($LASTEXITCODE -ne 0) { throw 'Android APK packaging failed.' }
    } finally { Pop-Location }
    $releaseDir = Join-Path $projectRoot 'releases'
    New-Item -ItemType Directory -Force -Path $releaseDir | Out-Null
    Copy-Item -LiteralPath (Join-Path $projectRoot 'src-tauri/gen/android/app/build/outputs/apk/arm64/debug/app-arm64-debug.apk') -Destination (Join-Path $releaseDir 'Elsewhere-Android-arm64-preview.apk')
    Write-Output (Join-Path $releaseDir 'Elsewhere-Android-arm64-preview.apk')
} finally { Pop-Location }
